import {
  BUILTIN_THEME_PREFIX,
  type Theme,
  type ThemeInput,
  themeInputSchema,
} from "./workspace-appearance";

const EPOCH = "2026-11-01T00:00:00.000Z";

function builtin(slug: string, input: ThemeInput): Theme {
  return {
    ...themeInputSchema.parse(input),
    id: `${BUILTIN_THEME_PREFIX}${slug}`,
    builtin: true,
    createdBy: "owner",
    createdAt: EPOCH,
    updatedAt: EPOCH,
  };
}

