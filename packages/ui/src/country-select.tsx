/** Regional-indicator pair, e.g. "PT" → 🇵🇹. */
function flag(code: string) {
  return String.fromCodePoint(
    ...[...code].map((letter) => 0x1f1a5 + letter.charCodeAt(0)),
  );
}

export function useCountryOptions(codes = COUNTRY_CODES): SearchSelectOption[] {
  return useMemo(() => {
    const names = new Intl.DisplayNames(["en"], { type: "region" });
    return codes
      .map((code) => {
        const name = names.of(code) ?? code;
        return {
          value: code,
          label: `${flag(code)}  ${name}`,
          keywords: `${code} ${name}`,
          meta: code,
        };
      })
      .sort((left, right) => left.keywords.localeCompare(right.keywords));
  }, [codes]);
}

export function CountrySelect({
  value,
  onValueChange,
  codes,
  disabled,
  className,
  id,
}: {
  value: string;
  onValueChange: (value: string) => void;
  codes?: string[];
  disabled?: boolean;
  className?: string;
  id?: string;
}) {
  const options = useCountryOptions(codes);
  return (
    <SearchSelect
      id={id}
      aria-label="Country"
      value={value}
      onValueChange={onValueChange}
      options={options}
      placeholder="Country"
      searchPlaceholder="Search countries"
      emptyLabel="No country"
      disabled={disabled}
      className={className}
    />
  );
}
