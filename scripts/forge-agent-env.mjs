#!/usr/bin/env node
import { chmodSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Renders the deploy host's `agent.env` from the values already in the root
 * `.env`, so the shared secret is copied rather than retyped.
 *
 * Only the genuinely shared values carry over. Everything the dev box sets for
 * itself — loopback addresses, a macOS Docker data root, build directories
 * under the home folder — is replaced with the production value, because
 * carrying those across is how a host ends up building into a path that does
 * not exist and reporting free space for a disk it is not using.
 *
 * Secrets are read and written, never printed.
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, ".env");
const target = resolve(root, "infra/systemd/forge-agent.env");

function readEnv(path) {
  const values = {};
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (!match) continue;
    const raw = match[2];
    const quoted = raw.match(/^(["'])([\s\S]*)\1/);
    values[match[1]] = quoted ? quoted[2] : raw.replace(/\s+#.*$/, "").trim();
  }
  return values;
}

const env = readEnv(source);
const arg = (name) =>
  process.argv.find((entry) => entry.startsWith(`--${name}=`))?.split("=")[1];

const bind = arg("bind") ?? "REPLACE_WITH_TAILSCALE_IP";
const controlPlane = arg("control-plane") ?? "http://100.89.155.9:3001";
const buildStorage = arg("build-storage") ?? "hdd";
if (buildStorage !== "hdd" && buildStorage !== "ssd") {
  console.error("[forge-agent-env] --build-storage must be hdd or ssd");
  process.exit(1);
}
const maxConcurrentBuilds =
  arg("max-concurrent-builds") ??
  (buildStorage === "ssd" ? "2" : (env.MAX_CONCURRENT_BUILDS ?? "3"));

const token = env.AGENT_TOKEN ?? "";
if (token.length < 32) {
  console.error(
    `[forge-agent-env] AGENT_TOKEN in .env is ${token.length} chars; the agent refuses anything under 32`,
  );
  process.exit(1);
}
if (env.DEPLOY_AGENT_TOKEN && env.DEPLOY_AGENT_TOKEN !== token) {
  console.error(
    "[forge-agent-env] AGENT_TOKEN and DEPLOY_AGENT_TOKEN disagree; the agent would authenticate against nothing",
  );
  process.exit(1);
}

const contents = `# Generated by scripts/forge-agent-env.mjs — do not commit.
# Install at /etc/forge/agent.env, owned by root, mode 0640, group forge.

# Loopback, RFC1918, link-local or CGNAT only; a wildcard or public address is
# refused at startup. This is the Tailscale address the Pi dials.
AGENT_BIND_ADDRESS=${bind}
AGENT_PORT=${env.AGENT_PORT || "4010"}

# Shared with DEPLOY_AGENT_TOKEN on the control plane.
AGENT_TOKEN=${token}

# The Pi, over Tailscale. Requires API_BIND_ADDRESS on the Pi to be its
# Tailscale address rather than the 127.0.0.1 default, or this is refused.
CONTROL_PLANE_URL=${controlPlane}

# Concurrent *builds*, not concurrent deployments — a run hands its slot back
# the moment the image exists and finishes starting the container outside the
# cap. The SSD profile defaults to two so exports cannot monopolise the runtime
# disk. Keep this in step with BuildKit's worker-wide parallelism.
MAX_CONCURRENT_BUILDS=${maxConcurrentBuilds}

# Production paths. Deliberately not taken from .env: those are this laptop's.
BUILD_ROOT=/mnt/storage/forge/builds
LOG_ROOT=/mnt/storage/forge/logs
CACHE_ROOT=/mnt/storage/forge/cache
# tmpfs — a resolved env set must never reach the disk.
RUN_ENV_ROOT=/run/forge
DOCKER_SOCKET=/var/run/docker.sock
# statfs'd by /healthz.
DOCKER_DATA_ROOT=/var/lib/docker
# External worker. Its data-root is selected independently by
# /etc/forge/buildkit-storage.env, while --load keeps completed runtime images
# in DOCKER_DATA_ROOT.
BUILDX_BUILDER=forge-${buildStorage}
BUILDKIT_ENDPOINT=docker-container://forge-buildkit
# The global Bun mutex protects a rotational worker from random-I/O collapse.
# Per-target cache mounts can run concurrently once the worker is SSD-backed.
SERIALIZE_BUN_INSTALLS=${buildStorage === "hdd" ? "true" : "false"}
DOCKER_NETWORK=${env.DOCKER_NETWORK || "forge-apps"}

# Caddy's admin API is unauthenticated code execution; loopback is enforced.
CADDY_ADMIN_URL=http://127.0.0.1:2019
CADDY_LISTEN=${env.CADDY_LISTEN || ":8080"}
CADDY_STATE_PATH=/srv/forge/caddy/config.json

BUILD_MEMORY_LIMIT_MB=${env.BUILD_MEMORY_LIMIT_MB || "6144"}
MEMORY_HEADROOM_MB=${env.MEMORY_HEADROOM_MB || "1024"}
HEALTH_POLL_MS=${env.HEALTH_POLL_MS || "2000"}
CONTAINER_DRAIN_MS=${env.CONTAINER_DRAIN_MS || "10000"}
CLAIM_POLL_MS=${env.CLAIM_POLL_MS || "3000"}
HEARTBEAT_MS=${env.HEARTBEAT_MS || "30000"}
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, contents);
chmodSync(target, 0o600);

console.log(`[forge-agent-env] wrote ${target} (0600)`);
console.log(`[forge-agent-env]   AGENT_BIND_ADDRESS=${bind}`);
console.log(`[forge-agent-env]   CONTROL_PLANE_URL=${controlPlane}`);
console.log(`[forge-agent-env]   BUILD_STORAGE=${buildStorage}`);
console.log(
  `[forge-agent-env]   AGENT_TOKEN carried from .env (${token.length} chars)`,
);
if (bind.startsWith("REPLACE")) {
  console.log(
    "[forge-agent-env] rerun with --bind=<tailscale ip of the deploy host> before copying",
  );
}
